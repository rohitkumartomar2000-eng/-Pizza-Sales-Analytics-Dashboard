create table pizza_data(
pizza_id INT ,
order_id INT,
pizza_name_id VARCHAR(50),
quantity INT,
order_date	DATE,
order_time TIME,
unit_price DECIMAL(10,2),
total_price	DECIMAL(10,2),
pizza_size VARCHAR(5),
pizza_category	VARCHAR(20),
pizza_ingredients VARCHAR(255),
pizza_name VARCHAR (50)
);

select * from pizza_data


--1. Total Revenue:
SELECT SUM(TOTAL_PRICE) AS TOTAL_REVENUE 
FROM PIZZA_DATA

---2. Average Order Value
SELECT SUM(TOTAL_PRICE) / COUNT(DISTINCT ORDER_ID) AS AVG_ORDER_VALUE
FROM PIZZA_DATA


---3. Total Pizzas Sold
SELECT SUM(QUANTITY) AS TOTAL_PIZZA_SOLD
FROM PIZZA_DATA


---4. Total Orders
SELECT COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS
FROM PIZZA_DATA

---5. Average Pizzas Per Order
SELECT CAST(CAST(SUM(QUANTITY)AS DECIMAL(10,2))
/ CAST(COUNT(DISTINCT ORDER_ID) AS DECIMAL(10,2)) AS DECIMAL(10,2)) AS AVG_PIZZA_PER_ORDER
FROM PIZZA_DATA


----B. Daily Trend for Total Orders
SELECT TO_CHAR(ORDER_DATE,'DAY') AS ORDER_DAY,
COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS
FROM PIZZA_DATA
GROUP BY ORDER_DAY

---C. Monthly Trend for Orders
SELECT TO_CHAR(ORDER_DATE,'MONTH') AS ORDER_MONTH,
COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS
FROM PIZZA_DATA
GROUP BY ORDER_MONTH

--D. % of Sales by Pizza Category
SELECT PIZZA_CATEGORY, 
CAST(SUM(TOTAL_PRICE) AS DECIMAL(10,2)) AS TOTAL_REVENUE,
CAST(SUM(TOTAL_PRICE) * 100 / (SELECT SUM(TOTAL_PRICE) FROM PIZZA_DATA) AS DECIMAL(10,2)) AS PCT
FROM PIZZA_DATA
GROUP BY PIZZA_CATEGORY


---E. % of Sales by Pizza Size
SELECT PIZZA_SIZE,
CAST(SUM(TOTAL_PRICE) AS DECIMAL(10,2)) AS TOTAL_REVENUE,
CAST(SUM(TOTAL_PRICE) * 100 / (SELECT SUM(TOTAL_PRICE) FROM PIZZA_DATA) AS DECIMAL(10,2)) AS PCT
FROM PIZZA_DATA
GROUP BY PIZZA_SIZE
ORDER BY PIZZA_SIZE


---F. Total Pizzas Sold by Pizza Category
SELECT PIZZA_CATEGORY,
SUM(QUANTITY) AS TOTAL_OTY
FROM PIZZA_DATA
GROUP BY PIZZA_CATEGORY
ORDER BY TOTAL_OTY DESC

--G. Top 5 Pizzas by Revenue
SELECT PIZZA_NAME,
SUM(TOTAL_PRICE) AS TOTAL_REVENUE FROM PIZZA_DATA
GROUP BY PIZZA_NAME
ORDER BY TOTAL_REVENUE DESC
LIMIT 5;

--H. Bottom 5 Pizzas by Revenue
SELECT PIZZA_NAME,
SUM(TOTAL_PRICE) AS TOTAL_REVENUE FROM PIZZA_DATA
GROUP BY PIZZA_NAME
ORDER BY TOTAL_REVENUE ASC
LIMIT 5;

---I. Top 5 Pizzas by Quantity
SELECT PIZZA_NAME,
SUM(QUANTITY) AS TOTAL_OTY
FROM PIZZA_DATA
GROUP BY PIZZA_NAME
ORDER BY TOTAL_OTY DESC
LIMIT 5;

---J. Bottom 5 Pizzas by Quantity
SELECT PIZZA_NAME,
SUM(QUANTITY) AS TOTAL_OTY
FROM PIZZA_DATA
GROUP BY PIZZA_NAME
ORDER BY TOTAL_OTY ASC
LIMIT 5;


---K. Top 5 Pizzas by Total Orders
SELECT PIZZA_NAME,
COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDER
FROM PIZZA_DATA
GROUP BY PIZZA_NAME
ORDER BY TOTAL_ORDER DESC
LIMIT 5;

